export const LARGEUR = 496
export const HAUTEUR = 638

// Coin nord-ouest de l'île : il correspond au point (MARGE, MARGE)
const LATITUDE_NORD = -12.63659
const LONGITUDE_OUEST = 45.01833
const MARGE = 42
// 1 degré de latitude = 1500 unités du dessin
const ECHELLE = 1500
// Un degré de longitude est un peu plus court qu'un degré de
// latitude (cosinus de la latitude de Mayotte, environ 12,8° sud)
const COSINUS = Math.cos((-12.82 * Math.PI) / 180)

export function projeter(coordonnees) {
  const latitude = coordonnees[0]
  const longitude = coordonnees[1]
  return {
    x: (longitude - LONGITUDE_OUEST) * COSINUS * ECHELLE + MARGE,
    y: (LATITUDE_NORD - latitude) * ECHELLE + MARGE
  }
}

